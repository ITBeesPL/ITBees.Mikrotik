using System.Text;

namespace ITBees.Mikrotik.WireGuard;

/// <summary>One parking router as seen by the central VPN hub.</summary>
public sealed record WireGuardHubPeer(string Name, string PublicKey, string? PresharedKey, IReadOnlyList<string> AllowedIps)
{
    /// <summary>wg-quick [Peer] section for /etc/wireguard/wg0.conf on the hub.</summary>
    public string ToWgQuickSection()
    {
        var sb = new StringBuilder();
        sb.Append("[Peer]\n");
        sb.Append("# ").Append(Name).Append('\n');
        sb.Append("PublicKey = ").Append(PublicKey).Append('\n');
        if (!string.IsNullOrEmpty(PresharedKey))
            sb.Append("PresharedKey = ").Append(PresharedKey).Append('\n');
        sb.Append("AllowedIPs = ").Append(string.Join(", ", AllowedIps)).Append('\n');
        return sb.ToString();
    }

    /// <summary>Command adding the peer to a running hub without restarting it.</summary>
    public string ToWgSetCommand(string hubInterface = "wg0")
    {
        var psk = string.IsNullOrEmpty(PresharedKey) ? string.Empty : " preshared-key <(echo '" + PresharedKey + "')";
        return $"wg set {hubInterface} peer {PublicKey}{psk} allowed-ips {string.Join(",", AllowedIps)}";
    }

    /// <summary>RouterOS commands when the hub is itself a MikroTik (CHR or hardware).</summary>
    public string ToRouterOsCommand(string hubInterface = "wg-hub")
    {
        var psk = string.IsNullOrEmpty(PresharedKey) ? string.Empty : $" preshared-key=\"{PresharedKey}\"";
        return $"/interface wireguard peers add interface={hubInterface} public-key=\"{PublicKey}\"{psk} allowed-address={string.Join(",", AllowedIps)} comment=\"{Name}\"";
    }
}

/// <summary>Builds the hub side of the tunnel (Linux wg-quick).</summary>
public static class WireGuardHubConfig
{
    /// <summary>
    /// Complete wg-quick configuration for a Linux hub: one interface, every parking router as a peer.
    /// Enable IP forwarding (net.ipv4.ip_forward=1) on the hub so it can route between the VPN and site LANs.
    /// </summary>
    public static string BuildWgQuickConfig(string hubPrivateKey, string hubAddress, int listenPort, IEnumerable<WireGuardHubPeer> peers)
    {
        if (!WireGuardKeys.IsValidKey(hubPrivateKey))
            throw new ArgumentException("Invalid hub private key.", nameof(hubPrivateKey));
        var sb = new StringBuilder();
        sb.Append("[Interface]\n");
        sb.Append("# Octopark parking VPN hub, generated by ITBees.Mikrotik\n");
        sb.Append("Address = ").Append(hubAddress).Append('\n');
        sb.Append("ListenPort = ").Append(listenPort).Append('\n');
        sb.Append("PrivateKey = ").Append(hubPrivateKey).Append('\n');
        foreach (var peer in peers)
            sb.Append('\n').Append(peer.ToWgQuickSection());
        return sb.ToString();
    }
}
